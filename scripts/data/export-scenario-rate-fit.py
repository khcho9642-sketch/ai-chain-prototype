"""Publish the four budget owners' fitted parameters from the private rate-capex analysis.

Run fit.py in rate-capex-fit first (annual DB reconciliation, SEC quarters, daily
EFFR and Newey-West intervals). Pass that directory to this script. No raw DB
records or individual quarterly observations are needed by the browser.
"""
import argparse
import csv
import json
from datetime import date, timedelta
from pathlib import Path


def read_csv(path):
    with path.open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def export(fit_dir):
    owners = ("MSFT", "AMZN", "GOOGL", "META")
    estimates = {row["ticker"]: row for row in read_csv(fit_dir / "estimates.csv")}
    quarters = read_csv(fit_dir / "quarter-inputs.csv")
    common_end = min(estimates[owner]["last_outcome"] for owner in owners)
    rows = []
    for owner in owners:
        fit = estimates[owner]
        year = sorted((q for q in quarters if q["ticker"] == owner and q["end"] <= common_end),
                      key=lambda q: q["end"])[-4:]
        if len(year) != 4 or year[-1]["end"] != common_end or any(
            date.fromisoformat(b["start"]) - date.fromisoformat(a["end"]) != timedelta(days=1)
            for a, b in zip(year, year[1:])
        ):
            raise ValueError(f"Incomplete common four-quarter CAPEX window for {owner}")
        cash_capex = sum(int(q["capex_usd"]) for q in year)
        if cash_capex <= 0 or int(fit["n"]) < 5:
            raise ValueError(f"Invalid CAPEX or regression sample for {owner}")
        rows.append(dict(companyId=owner, logBeta=float(fit["beta_log"]),
                         low95Pct=float(fit["lo95"]), high95Pct=float(fit["hi95"]),
                         cashCapexUsd=cash_capex, observations=int(fit["n"]),
                         firstOrigin=fit["start"], lastOrigin=fit["last_origin"],
                         budgetStart=year[0]["start"], budgetEnd=year[-1]["end"]))
    return "// Generated by scripts/data/export-scenario-rate-fit.py\nexport const RATE_CAPEX_FITS = " + json.dumps(rows, indent=2, allow_nan=False) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("fit_dir", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] / "assets/scenario-rate-fits.js")
    args = parser.parse_args()
    args.output.write_text(export(args.fit_dir), encoding="utf-8")
