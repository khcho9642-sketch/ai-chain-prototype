import { DatabaseSync } from 'node:sqlite'
import { rename, writeFile, rm } from 'node:fs/promises'
import { randomUUID } from 'node:crypto'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { publicSource } from './export-scenario-financials.mjs'

function filingUrl(row) {
  const u = new URL(row.source_url)
  if (u.protocol !== 'https:' || u.username || u.password || u.port) return null
  if (row.selected_provider_id === 'DART' && u.hostname === 'opendart.fss.or.kr') {
    const receipt = JSON.parse(row.metadata_json || '{}').sourceAccession
    return /^\d{14}$/.test(receipt) ? 'https://dart.fss.or.kr/dsaf001/main.do?rcpNo=' + receipt : null
  }
  if (row.selected_provider_id === 'ISSUER_IR' && u.hostname === 'download.schneider-electric.com' && u.pathname === '/files') {
    const ref = u.searchParams.get('p_Doc_Ref')
    if (!/^[\w-]+$/.test(ref || '')) return null
    return u.origin + '/files?p_Doc_Ref=' + ref + (/^#page=\d+$/.test(u.hash) ? u.hash : '')
  }
  return publicSource(row, row.ticker)?.url
}

export function exportCompanyFinancials(db) {
  const companies = Object.fromEntries(db.prepare('SELECT company_id FROM companies ORDER BY company_id').all().map(row => [row.company_id, []]))
  const yearByPeriod = new Map()
  const periods = db.prepare(`SELECT * FROM v_completed_annual_periods_5y
    ORDER BY company_id, fiscal_year DESC, CASE statement_scope WHEN 'consolidated' THEN 0 ELSE 1 END, period_end_date DESC`).all()
  for (const period of periods) {
    const years = companies[period.company_id]
    if (years.some(year => year.fiscalYear === period.fiscal_year) || years.length === 5) continue
    const year = { fiscalYear: period.fiscal_year, end: period.period_end_date, scope: period.statement_scope, currency: period.presentation_currency, facts: {} }
    years.push(year)
    yearByPeriod.set(period.period_id, year)
  }

  const rows = db.prepare(`SELECT f.*, d.source_url, date(d.retrieved_at) AS checked, r.metadata_json, l.ticker,
      EXISTS (SELECT 1 FROM reconciliation_issues i WHERE i.company_id = f.company_id AND i.resolution_status = 'open'
        AND (i.period_id IS NULL OR i.period_id = f.period_id) AND (i.metric_id IS NULL OR i.metric_id = f.metric_id)
        AND (i.requires_user_decision = 1 OR i.severity IN ('high', 'material'))) AS pending
    FROM v_financial_facts_5y f
    JOIN normalized_financial_observations n ON n.normalized_observation_id = f.selected_normalized_observation_id
      AND n.normalization_status = 'accepted' AND n.period_id = f.period_id AND n.metric_id = f.metric_id
    JOIN raw_financial_observations r ON r.raw_observation_id = n.raw_observation_id AND r.company_id = f.company_id
    JOIN source_documents d ON d.document_id = r.document_id AND d.provider_id = f.selected_provider_id AND d.company_id = f.company_id
    LEFT JOIN security_listings l ON l.company_id = f.company_id AND l.is_primary = 1
    WHERE f.metric_id IN ('revenue', 'operating_income', 'operating_cash_flow')
    ORDER BY f.company_id, f.fiscal_year DESC, f.metric_id`).all()
  let asOf = ''
  for (const row of rows) {
    const year = yearByPeriod.get(row.period_id)
    if (!year) continue
    if (row.pending) {
      year.facts[row.metric_id] = { pending: true }
      continue
    }
    const value = Number(row.value_text) * 10 ** row.scale_exponent
    const url = filingUrl(row)
    if (!row.value_text.trim() || !Number.isFinite(value) || !url || row.currency !== year.currency || row.statement_scope !== year.scope) {
      throw new Error('재무 수치 또는 원문 확인 필요 · ' + row.company_id + ' ' + row.fiscal_year + ' ' + row.metric_id)
    }
    year.facts[row.metric_id] = { value, url, provider: row.selected_provider_id }
    if (row.checked > asOf) asOf = row.checked
  }
  if (!asOf) throw new Error('출처가 확인된 재무 수치가 없습니다.')
  return { asOf, companies }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { values } = parseArgs({ options: { db: { type: 'string' }, output: { type: 'string' } } })
  const db = new DatabaseSync(values.db || '.local/financials/financials.sqlite', { readOnly: true })
  let snapshot
  try { db.exec('BEGIN'); snapshot = exportCompanyFinancials(db); db.exec('COMMIT') } finally { db.close() }
  const output = values.output || fileURLToPath(new URL('../../assets/company-financial-snapshot.js', import.meta.url))
  const temp = output + '.' + randomUUID() + '.tmp'
  try {
    const rows = Object.entries(snapshot.companies).map(([id, years]) => '  ' + JSON.stringify(id) + ': ' + JSON.stringify(years))
    await writeFile(temp, '// Generated by scripts/data/export-company-financials.mjs\nexport const asOf = ' + JSON.stringify(snapshot.asOf) + '\nexport const yearsById = {\n' + rows.join(',\n') + '\n}\n', { flag: 'wx' })
    await rename(temp, output)
  } finally { await rm(temp, { force: true }) }
  console.log(Object.keys(snapshot.companies).length + '개사 · 기준일 ' + snapshot.asOf)
}
